# Day 3 - Python User Input

# Getting text from the user
name = input("Enter your name: ")

# Getting numbers from the user
age = int(input("Enter your age: "))

# Getting a decimal number
height = float(input("Enter your height in feet: "))

# Displaying the information
print()
print("----- My Details -----")
print("Name:", name)
print("Age:", age)
print("Height:", height)

# Simple calculation
age_after_5_years = age + 5

print("Your age after 5 years:", age_after_5_years)